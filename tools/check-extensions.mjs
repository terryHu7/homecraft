import assert from 'node:assert/strict';
import { mkdtempSync, realpathSync, rmSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { initialize } from './extensions.mjs';
import { json, writeJSON, pack, install, change } from './extensions-lib.mjs';
import { copySite, serve, launchOffline, offlineContext, boot } from './extension-browser.mjs';

const work = mkdtempSync(join(realpathSync(tmpdir()), 'homecraft-browser-'));
const site = join(work, 'site'), report = fileURLToPath(new URL('./.check/extensions/', import.meta.url));
mkdirSync(report, { recursive: true }); copySite(site);
const server = await serve(site), browser = await launchOffline();
const results = [];
try {
  const context = await offlineContext(browser, { viewport: { width: 1280, height: 800 } }), page = await context.newPage(), errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message)); page.on('request', request => requests.push(request.url()));
  await boot(page, server.url);
  assert.deepEqual(await page.evaluate(() => __home.extensions.status()), []);
  assert(!requests.some(url => url.includes('/extensions/')));
  results.push('Default template imports no extension packages');
  function add(name, code, capabilities = ['ui']) {
    const id = `test.${name}`, folder = join(work, name), bundle = join(work, `${name}.json`);
    initialize(folder, id); const manifest = json(join(folder, 'manifest.json')); manifest.capabilities = capabilities;
    writeJSON(join(folder, 'manifest.json'), manifest); writeFileSync(join(folder, 'index.js'), code);
    pack(folder, bundle); install({ site, bundle });
  }
  add('panel', `export function activate(api) {
    const output = api.ui.status({en: 'Extension ready', zh: '扩展就绪'});
    api.ui.button({en: 'Test action', zh: '测试操作'}, () => output.set({en: 'Action complete', zh: '操作完成'}));
    const marker = api.scene.marker(); marker.set({x: 1, y: 0, z: 1, heading: 0});
    window.__extensionTicks = 0; api.interval(() => window.__extensionTicks++, 100);
  }`, ['ui', 'scene.markers']);
  add('activation-error', `export function activate(api) { api.ui.status('Should be removed'); throw Error('Activation fixture'); }`);
  add('frame-error', `export function activate(api) { api.ui.status('Should be removed'); api.onFrame(() => { throw Error('Frame fixture'); }); }`);
  add('undeclared', `export function activate(api) { api.ui.status('Should not appear'); }`, []);
  add('syntax-error', `export function activate( {`);
  await boot(page, server.url + '/?lang=en');
  await page.waitForFunction(() => __home.extensions.status().find(e => e.id === 'test.frame-error')?.state === 'failed');
  const states = await page.evaluate(() => __home.extensions.status());
  assert.equal(states.filter(e => e.state === 'failed').length, 4);
  assert.equal(states.find(e => e.id === 'test.panel').state, 'active');
  assert.equal(await page.locator('#homecraft-extensions > *').count(), 2);
  await page.waitForTimeout(4200);
  await page.getByRole('button', { name: 'Test action', exact: true }).click();
  assert.equal(await page.locator('output[data-extension="test.panel"]').textContent(), 'Action complete');
  await page.evaluate(async () => (await import('/engine/lang.js')).setLang('zh'));
  assert.equal(await page.locator('output[data-extension="test.panel"]').textContent(), '操作完成');
  await page.screenshot({ path: join(report, 'desktop.png') });
  await page.evaluate(() => __home.go('about'));
  assert(await page.locator('#panel').evaluate(el => el.open));
  await page.evaluate(() => document.querySelector('#panel .close').click());
  results.push('Activation, syntax, frame and capability failures leave core navigation and healthy extensions working');
  await page.evaluate(() => __home.extensions.stop('test.panel'));
  const ticks = await page.evaluate(() => window.__extensionTicks);
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => window.__extensionTicks), ticks);
  assert.equal(await page.locator('#homecraft-extensions').count(), 0);
  assert.equal(await page.evaluate(() => __home.stage.scene.children.filter(c => c.name.startsWith('extension:')).length), 0);
  change({ site, id: 'test.panel', operation: 'disable' }); requests.length = 0;
  await boot(page, server.url);
  assert(!requests.some(url => url.includes('/extensions/test.panel/')));
  results.push('Disposal removes controls, timers and geometry; disabled packages are never requested');
  change({ site, id: 'test.panel', operation: 'enable' });
  const mobileContext = await offlineContext(browser, { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true }), mobile = await mobileContext.newPage();
  mobile.on('pageerror', error => errors.push(error.message));
  await boot(mobile, server.url + '/?lang=zh'); await mobile.waitForTimeout(4200);
  const bounds = await mobile.locator('#homecraft-extensions').boundingBox();
  assert(bounds && bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y + bounds.height < 844);
  await mobile.screenshot({ path: join(report, 'mobile.png') });
  const stats = await mobile.evaluate(() => __home.stats()); assert(stats.calls <= 60 && stats.triangles <= 200000);
  assert.deepEqual(errors, []); results.push({ mobile: 'Passed', stats });
  await mobileContext.close(); await context.close();
  writeJSON(join(report, 'report.json'), { passed: true, results });
  console.log(JSON.stringify({ passed: true, results, report }, null, 2));
} finally { await browser.close(); await server.close(); rmSync(work, { recursive: true, force: true }); }
